package determination.xenon.mindustry.mod;

import com.google.gson.JsonSyntaxException;
import determination.xenon.mindustry.download.MirrorSelector;
import determination.xenon.util.logging.Logger;
import org.jetbrains.annotations.NotNullByDefault;
import org.jetbrains.annotations.Nullable;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.time.Duration;
import java.util.LinkedHashSet;
import java.util.Objects;
import java.util.Set;

/// Fetches the Xenon recommendation snapshot from the project repository.
///
/// The document is generated by `scripts/mod-ranking/generate.mjs` and hosted
/// at `remote/mod-ranking.json` on `main`. A successful refresh is persisted to
/// `<cacheRoot>/mods/mod-ranking.json`; a failed refresh replays that cache so
/// the mod browser keeps its last known ranking while offline.
///
/// The repository deliberately mirrors [MindustryModsIndexRepository]'s
/// cache-first/fallback behavior so both datasets fail independently: a broken
/// ranking must never blank the mod list.
@NotNullByDefault
public final class MindustryModRankingRepository {

    /// Upstream URL of the generated recommendation snapshot. The owner/repo
    /// matches `Metadata.PUBLISH_URL`; XenonCore cannot reference the UI module.
    public static final String RANKING_URL =
            "https://raw.githubusercontent.com/DeterMination-Wind/Xenon/main/remote/mod-ranking.json";

    private static final Duration CONNECT_TIMEOUT = Duration.ofSeconds(10);
    private static final Duration READ_TIMEOUT = Duration.ofSeconds(30);

    private final HttpClient http;
    private final MirrorSelector mirror;
    private final @Nullable Path cacheFile;

    /// Most recent successful snapshot; never `null`.
    private volatile MindustryModRanking snapshot = MindustryModRanking.empty();

    /// @param cacheRoot launcher caches root (for example
    ///                  `Metadata.getCachesDirectory()`); may be `null` to
    ///                  disable on-disk caching
    public MindustryModRankingRepository(@Nullable Path cacheRoot) {
        this(cacheRoot, MirrorSelector.getInstance());
    }

    /// Creates a repository with an injected mirror selector (tests, mocks).
    ///
    /// @param cacheRoot launcher caches root, or `null`
    /// @param mirror    mirror selector, never `null`
    public MindustryModRankingRepository(@Nullable Path cacheRoot, MirrorSelector mirror) {
        this.mirror = Objects.requireNonNull(mirror, "mirror");
        this.cacheFile = cacheRoot == null
                ? null
                : cacheRoot.resolve("mods").resolve("mod-ranking.json");
        this.http = HttpClient.newBuilder()
                .followRedirects(HttpClient.Redirect.NORMAL)
                .connectTimeout(CONNECT_TIMEOUT)
                .build();
    }

    /// Refreshes from the network, falling back to the on-disk cache.
    ///
    /// @return the parsed snapshot, never `null`
    /// @throws IOException when both the network and the cache are unavailable
    public MindustryModRanking refresh() throws IOException {
        String body;
        IOException networkError = null;
        try {
            body = fetch();
        } catch (IOException error) {
            networkError = error;
            body = readCachedBody();
            if (body == null) throw error;
            Logger.LOG.warning("Failed to fetch mod ranking, serving cached copy: "
                    + error.getMessage());
        }

        MindustryModRanking parsed;
        try {
            parsed = MindustryModRanking.parse(body);
        } catch (JsonSyntaxException error) {
            String cached = readCachedBody();
            if (cached != null && !cached.equals(body)) {
                Logger.LOG.warning("Mod ranking parse failed, replaying cache: "
                        + error.getMessage());
                parsed = MindustryModRanking.parse(cached);
            } else {
                throw new IOException("Malformed mod ranking: " + error.getMessage(), error);
            }
        }

        if (networkError == null) {
            writeCache(body);
        }
        publish(parsed);
        return parsed;
    }

    /// Loads the cached snapshot without touching the network.
    ///
    /// @return the parsed cache, or the empty snapshot when unavailable
    public MindustryModRanking loadCache() {
        String body = readCachedBody();
        if (body == null || body.isBlank()) return snapshot;
        try {
            MindustryModRanking parsed = MindustryModRanking.parse(body);
            publish(parsed);
            return parsed;
        } catch (RuntimeException error) {
            Logger.LOG.warning("Failed to parse cached mod ranking: " + error.getMessage());
            return snapshot;
        }
    }

    /// Most recent snapshot without triggering a refresh.
    public MindustryModRanking current() {
        return snapshot;
    }

    /// Fetches the first reachable candidate URL.
    private String fetch() throws IOException {
        IOException lastError = null;
        for (URI uri : fetchCandidates()) {
            try {
                return fetch(uri);
            } catch (IOException error) {
                if (lastError == null) lastError = error;
                Logger.LOG.warning("Mod ranking source failed (" + uri.getHost()
                        + "): " + error.getMessage());
            }
        }
        throw lastError == null ? new IOException("No mod ranking source available") : lastError;
    }

    /// Candidate URLs in order: whichever GitHub mirror the selector picked,
    /// then the direct raw URL. Duplicates are dropped.
    private Set<URI> fetchCandidates() {
        Set<URI> uris = new LinkedHashSet<>();
        uris.add(URI.create(mirror.wrap(RANKING_URL)));
        uris.add(URI.create(RANKING_URL));
        return uris;
    }

    /// Executes one HTTP GET and returns the UTF-8 body.
    private String fetch(URI uri) throws IOException {
        HttpRequest request = HttpRequest.newBuilder(uri)
                .GET()
                .timeout(READ_TIMEOUT)
                .header("Accept", "application/json")
                .header("User-Agent", "Xenon-Launcher")
                .build();
        HttpResponse<String> response;
        try {
            response = http.send(request, HttpResponse.BodyHandlers.ofString(StandardCharsets.UTF_8));
        } catch (InterruptedException error) {
            Thread.currentThread().interrupt();
            throw new IOException("Interrupted contacting " + uri, error);
        }
        if (response.statusCode() / 100 != 2) {
            throw new IOException("HTTP " + response.statusCode() + " from " + uri);
        }
        return response.body();
    }

    /// Reads the cached body, or `null` when caching is disabled or unavailable.
    private @Nullable String readCachedBody() {
        Path file = cacheFile;
        if (file == null || !Files.isRegularFile(file)) return null;
        try {
            return Files.readString(file, StandardCharsets.UTF_8);
        } catch (IOException error) {
            Logger.LOG.warning("Failed to read cached mod ranking: " + error.getMessage());
            return null;
        }
    }

    /// Persists the raw body after a successful network refresh.
    private void writeCache(String body) {
        Path file = cacheFile;
        if (file == null) return;
        try {
            Path parent = file.getParent();
            if (parent != null) Files.createDirectories(parent);
            Files.writeString(file, body, StandardCharsets.UTF_8,
                    StandardOpenOption.CREATE,
                    StandardOpenOption.TRUNCATE_EXISTING,
                    StandardOpenOption.WRITE);
        } catch (IOException error) {
            Logger.LOG.warning("Failed to persist mod ranking cache: " + error.getMessage());
        }
    }

    /// Publishes one snapshot to concurrent readers.
    private void publish(MindustryModRanking ranking) {
        this.snapshot = ranking;
    }
}
